"""Run with the host Playwright package and an already running local test server."""
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
    page=browser.new_page(viewport={'width':1440,'height':1100},device_scale_factor=1)
    errors=[];page.on('pageerror',lambda error:errors.append(str(error)))
    page.request.delete('http://127.0.0.1:8000/api/profiles/local')
    page.goto('http://127.0.0.1:8000',wait_until='networkidle')
    page.screenshot(path=str(ROOT/'reports/dashboard-desktop.png'),full_page=True)
    page.locator('nav button[data-view="profile"]').click()
    page.locator('[name="name"]').fill('Browser Test')
    page.locator('[name="sex"]').select_option('female')
    page.locator('#step-next').click()
    page.locator('#condition-search').fill('hypertension')
    page.locator('input[value="hypertension"]').check()
    page.locator('[name="allergies"]').fill('peanut')
    page.locator('#step-next').click()
    page.locator('#save-profile').click()
    page.wait_for_selector('#overview:not(.hidden)')
    assert 'Browser Test' in page.locator('#guidance').inner_text()
    page.locator('nav button[data-view="analyze"]').click()
    page.locator('#food-select').select_option('rice')
    page.locator('#grams-exact').fill('180')
    page.locator('#add-item').click()
    page.locator('#calculate').click()
    page.wait_for_selector('#meal-result .result-grid')
    assert '234' in page.locator('#meal-result').inner_text()
    page.locator('#log-meal').click()
    page.locator('#meal-items .item-row').wait_for(state='detached')
    page.locator('nav button[data-view="history"]').click()
    page.wait_for_selector('.journal-card')
    assert 'Cooked white rice' in page.locator('#history-results').inner_text()
    page.locator('nav button[data-view="plan"]').click()
    page.locator('#generate-plan').click()
    page.wait_for_selector('#plan-results .plan-card, #plan-results .notice')
    assert page.locator('#plan-results').inner_text()
    page.locator('nav button[data-view="overview"]').click()
    page.screenshot(path=str(ROOT/'reports/dashboard-populated.png'),full_page=True)
    page.set_viewport_size({'width':390,'height':844})
    page.screenshot(path=str(ROOT/'reports/dashboard-mobile.png'),full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Mobile overflow'
    assert not errors, errors
    browser.close()
    print('Browser checks passed: desktop and mobile, onboarding, condition selection, meal calculation, journal persistence, plan request, no JavaScript errors, no horizontal overflow.')
